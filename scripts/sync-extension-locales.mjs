import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { translate, resolveLanguage } from '../locales/runtime.mjs';
import { languages, catalogues, jsKeys } from './check-locales.mjs';
if (process.exitCode) process.exit(process.exitCode);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
for (const directory of ['extension', 'extension-firefox']) {
  const popup = path.join(root, directory, 'popup.js');
  const keys = new Set(jsKeys(popup));
  for (const match of fs.readFileSync(path.join(root, directory, 'popup.html'), 'utf8').matchAll(/data-i18n="([^"]+)"/g)) keys.add(match[1]);
  const subset = Object.fromEntries(Object.entries(catalogues).map(([code, catalogue]) => [code,
    Object.fromEntries([...keys].filter(key => catalogue[key]).map(key => [key, catalogue[key]]))]));
  const bundle = `// Generated by scripts/sync-extension-locales.mjs. Edit locales/*.json instead.\n` +
    `globalThis.BetterIliasI18n = (() => {\nconst languages = ${JSON.stringify(languages)};\n` +
    `const catalogues = ${JSON.stringify(subset)};\n${translate.toString()}\n${resolveLanguage.toString()}\n` +
    `let language = resolveLanguage(navigator.language, languages);\nreturn { languages, getLanguage: () => language, ` +
    `setLanguage: value => { language = resolveLanguage(value, languages); }, ` +
    `t: (key, values) => translate(catalogues, language, key, values) };\n})();\n`;
  fs.writeFileSync(path.join(root, directory, 'i18n.js'), bundle);
  for (const code of Object.keys(languages)) {
    const messages = Object.fromEntries(['description', 'title'].map(key => [key, { message: translate(catalogues, code, `extension.${key}`) }]));
    const target = path.join(root, directory, '_locales', code);
    fs.mkdirSync(target, { recursive: true });
    fs.writeFileSync(path.join(target, 'messages.json'), JSON.stringify(messages, null, 2) + '\n');
  }
}
